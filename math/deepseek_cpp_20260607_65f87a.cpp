        for (size_t i = 0; i < verts.size(); ++i) {
            if ((verts[i] - p).squaredLength() < T(1e-8)) return static_cast<uint32_t>(i);
        }
        verts.push_back(p);
        return static_cast<uint32_t>(verts.size() - 1);
