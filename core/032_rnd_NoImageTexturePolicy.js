// File : 032
// name : src/core/032_rnd_NoImageTexturePolicy.js
// description : Policy enforcement module that guarantees the anime lighting
//               stack NEVER depends on image textures (PNG / JPG / WebP /
//               KTX / DDS / HDR / EXR / Basis / ASTC / any bitmap format).
//               The entire visual identity is generated procedurally:
//               colors from the palette tables (016_rnd_Config.js + 019/020
//               profiles), gradients from shader math, noise from GLSL
//               functions, normals from geometry + quantization, occlusion
//               from algorithms, sky from scattering math. This module
//               audits the runtime to enforce that invariant and reports
//               violations before they reach the GPU.
//
//               Why this policy exists for Android mobile:
//                 • Zero image decode on the main thread — no jank from
//                   `new Image()` + canvas → texture upload.
//                 • Zero GPU memory spent on bitmaps — RT pool + geometry
//                   get the whole budget.
//                 • Zero network requests — no CDN stalls, no cache misses,
//                   no "texture not loaded yet" race conditions.
//                 • Deterministic boot: the engine is ready the moment
//                   shaders compile, no async texture-wait phase.
//                 • Deterministic look: the anime style is derived from
//                   numbers, not from pre-baked bitmaps, so it is
//                   resolution-independent and device-independent.
//                 • Smaller bundle: no image assets to ship, no atlas.
//
//               What counts as a violation:
//                 • `THREE.Texture` whose `image` is an HTMLImageElement,
//                   HTMLCanvasElement, HTMLVideoElement, ImageBitmap,
//                   OffscreenCanvas, or any object with `.width`/`.height`
//                   that is NOT a DataTexture or a derived procedural source.
//                 • `THREE.DataTexture` whose data is a bitmap payload
//                   (i.e. cloned from an image source). Allowed only if
//                   its `.userData.__procedural` flag is `true`.
//                 • `THREE.CompressedTexture` — always a violation
//                   (compressed textures are inherently bitmap-sourced).
//                 • `THREE.CubeTexture` built from image faces.
//                 • `THREE.TextureLoader`, `THREE.ImageLoader`,
//                   `THREE.CubeTextureLoader`, `THREE.HDRLoader`,
//                   `THREE.EXRLoader`, `THREE.RGBELoader`, `THREE.KTXLoader`,
//                   `THREE.DDSLoader`, `THREE.BasisTextureLoader` — the
//                   mere existence of these on the THREE namespace is
//                   flagged at boot (it means someone imported them).
//                 • Any `material.map`, `material.normalMap`,
//                   `material.roughnessMap`, `material.metalnessMap`,
//                   `material.emissiveMap`, `material.aoMap`,
//                   `material.alphaMap`, `material.envMap`,
//                   `material.lightMap`, `material.bumpMap`,
//                   `material.displacementMap`, `material.specularMap`
//                   that points to a bitmap-backed texture.
//
//               What is allowed:
//                 • `THREE.DataTexture` created with `userData.__procedural`
//                   = true (procedural palette LUTs, procedural noise LUTs,
//                   procedural gradient LUTs generated by CPU-side code).
//                 • `THREE.DataArrayTexture` with the same flag (for 3D LUTs
//                   used by color grading / GI probe grids).
//                 • `THREE.CanvasTexture` ONLY if its `userData.__procedural`
//                   is true AND its canvas was created from procedural math
//                   (no drawImage of an image source).
//                 • `THREE.WebGLRenderTarget.texture` — GPU-generated, not
//                   bitmap, and always allowed.
//                 • `THREE.DepthTexture` — allowed.
//
//               Enforcement modes:
//                 • AUDIT      — passive scan, records violations, no throw
//                 • WARN       — scan + log warning per violation
//                 • ENFORCE    — scan + throw on first violation
//                 • PARANOID   — scan at boot AND every N frames
//
//               The module exposes:
//                 • `markProcedural(texture)`   — flag a texture as
//                                                 procedurally generated
//                 • `isProcedural(texture)`     — query the flag
//                 • `auditThreeNamespace()`     — boot audit of THREE
//                 • `auditMaterial(material)`   — per-material scan
//                 • `auditScene(scene)`         — full scene traversal
//                 • `enforceNoImageTextures()`  — engine boot hook
//
//               All audits run OFF the per-frame hot path (boot + on-demand
//               from debug). Zero per-frame allocations on the render loop.
//
//               Strictly Three.js r185 lights only; strictly bitECS 0.4.0 API
//               only; no external policy libs; no image textures ever.
// best for : Guaranteeing on Android that the anime lighting stack never
//            allocates bitmap GPU memory, never waits on image decode,
//            and never accidentally ships an image dependency. The visual
//            quality comes from math, palette tables, and shader composition
//            — not from pre-baked bitmaps.
