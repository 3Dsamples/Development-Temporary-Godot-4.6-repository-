const PROCEDURAL_FLAG = '__procedural';
const PROCEDURAL_SOURCE = '__proceduralSource';

function _now() {
  return (typeof performance !== 'undefined' && typeof performance.now === 'function')
    ? performance.now()
    : Date.now();
}

function _isTexture(obj) {
  return !!obj && (obj.isTexture === true || obj.isCompressedTexture === true || obj.isCubeTexture === true);
}

function _isDataTexture(obj) {
  return !!obj && obj.isDataTexture === true;
}

function _isDataArrayTexture(obj) {
  return !!obj && obj.isDataArrayTexture === true;
}

function _isCubeTexture(obj) {
  return !!obj && obj.isCubeTexture === true;
}

function _isCompressedTexture(obj) {
  return !!obj && obj.isCompressedTexture === true;
}

function _isCanvasTexture(obj) {
  return !!obj && obj.isCanvasTexture === true;
}

function _isRenderTargetTexture(obj) {
  return !!obj && obj.isRenderTargetTexture === true;
}

function _isDepthTexture(obj) {
  return !!obj && obj.isDepthTexture === true;
}

function _isPMREM(obj) {
  return !!obj && obj.isPMREMGenerator === true;
}

function _isProceduralFlagged(obj) {
  if (!obj) return false;
  const ud = obj.userData;
  if (!ud) return false;
  if (ud[PROCEDURAL_FLAG] === true) return true;
  return false;
}

