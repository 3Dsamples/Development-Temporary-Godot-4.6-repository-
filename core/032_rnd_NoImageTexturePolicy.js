export class ViolationRecord {
  constructor() {
    this.kind       = VIOLATION_KIND.UNKNOWN;
    this.label      = null;
    this.object     = null;
    this.details    = null;
    this.frame      = 0;
    this.timeMs     = 0;
  }

  reset() {
    this.kind    = VIOLATION_KIND.UNKNOWN;
    this.label   = null;
    this.object  = null;
    this.details = null;
    this.frame   = 0;
    this.timeMs  = 0;
    return this;
  }
}

/* ------------------------------------------------------------------ */
/* 3. NO-IMAGE POLICY ENFORCER                                        */
/* ------------------------------------------------------------------ */

export class NoImageTexturePolicy {
  constructor(options = {}) {
    this.options = Object.assign({
      mode:              POLICY_MODE.WARN,
      channel:           LOG_CHANNEL.CORE,
      logViolations:     true,
      recordProfilerMark:true,
      throwOnViolation:  false,
      maxViolations:     MAX_VIOLATIONS,
      paranoidIntervalFrames: 600,
      allowCompressed:   false,
      allowCanvasTexture:false,
      allowPMREM:        true,
    }, options || {});

    this.mode   = this.options.mode;

    this.violations = new Array(this.options.maxViolations);
    for (let i = 0; i < this.options.maxViolations; i++) this.violations[i] = new ViolationRecord();
    this.violationHead  = 0;
    this.violationCount = 0;
    this.violationTotal = 0;

    this.auditCount       = 0;
    this.auditSceneCount  = 0;
    this.auditMaterialCount = 0;
    this.auditTextureCount  = 0;

    this.frame = 0;
    this.lastParanoidFrame = -1;

    this._listeners = new Map();

    this._boundary = null;
    if (this.options.throwOnViolation) {
      try {
        const mgr = getDefaultErrorBoundaries();
        if (mgr) {
          this._boundary = mgr.create('policy.no_image_texture', {
            tag: 12 /* BOUNDARY_TAG.REGISTRY */,
            failureThreshold: 1,
          });
        }
      } catch (_) { /* swallow */ }
    }
  }

  /* ---------------- events ---------------- */

  on(event, fn) {
    if (typeof event !== 'string' || typeof fn !== 'function') return () => {};
    let arr = this._listeners.get(event);
    if (!arr) { arr = []; this._listeners.set(event, arr); }
    arr.push(fn);
    return () => this.off(event, fn);
  }

  off(event, fn) {
    const arr = this._listeners.get(event);
    if (!arr) return;
    const i = arr.indexOf(fn);
    if (i >= 0) arr.splice(i, 1);
  }

  _emit(event, payload) {
    const arr = this._listeners.get(event);
    if (!arr) return;
    for (let i = 0; i < arr.length; i++) {
      try { arr[i](payload); } catch (_) { /* swallow */ }
    }
  }

  beginFrame(frameNumber) {
    this.frame = (typeof frameNumber === 'number') ? frameNumber : (this.frame + 1);

    if (this.mode === POLICY_MODE.PARANOID) {
      if ((this.frame - this.lastParanoidFrame) >= this.options.paranoidIntervalFrames) {
        this.lastParanoidFrame = this.frame;
        this._emit('paranoid-tick', { frame: this.frame });
      }
    }
  }

  /* ---------------- violation recording ---------------- */

  _record(kind, label, object, details) {
    const rec = this.violations[this.violationHead];
    rec.reset();
    rec.kind    = kind;
    rec.label   = label || VIOLATION_KIND_NAME[kind];
    rec.object  = object || null;
    rec.details = details || null;
    rec.frame   = this.frame;
    rec.timeMs  = _now();

    this.violationHead = (this.violationHead + 1) % this.options.maxViolations;
    if (this.violationCount < this.options.maxViolations) this.violationCount++;
    this.violationTotal++;

    if (this.options.logViolations && this.mode !== POLICY_MODE.AUDIT) {
      const log = getDefaultLogger();
      if (log) {
        log.warn(this.options.channel, () =>
          `[032_rnd_NoImageTexturePolicy] violation: ${VIOLATION_KIND_NAME[kind]} — ${rec.label}` +
          (details ? ` (${details})` : '')
        );
      }
    }

    if (this.options.recordProfilerMark) {
      try {
        const p = getDefaultProfiler();
        if (p) p.mark('policy_violation:' + VIOLATION_KIND_NAME[kind]);
      } catch (_) { /* swallow */ }
    }

    this._emit('violation', {
      kind:    VIOLATION_KIND_NAME[kind],
      label:   rec.label,
      details: rec.details,
      frame:   this.frame,
    });

    if (this.options.throwOnViolation && this.mode === POLICY_MODE.ENFORCE) {
      if (this._boundary) {
        this._boundary.run(() => {
          throw new Error(`[032_rnd_NoImageTexturePolicy] enforced: ${VIOLATION_KIND_NAME[kind]} — ${rec.label}`);
        });
      } else {
        throw new Error(`[032_rnd_NoImageTexturePolicy] enforced: ${VIOLATION_KIND_NAME[kind]} — ${rec.label}`);
      }
    }

    return false;
  }

  /* ---------------- procedural marking ---------------- */

  /**
   * Marks a texture (DataTexture, CanvasTexture, DataArrayTexture, or any
   * custom texture) as procedurally generated. This is the ONLY sanctioned
   * way to opt out of the bitmap policy.
   *
   *   markProcedural(myNoiseLUT, 'noise_lut');
   */
  markProcedural(texture, source) {
    if (!texture) return false;
    if (!texture.userData) texture.userData = {};
    texture.userData[PROCEDURAL_FLAG] = true;
    if (source) texture.userData[PROCEDURAL_SOURCE] = String(source);
    return true;
  }

  isProcedural(texture) {
    return _isProceduralFlagged(texture);
  }

  unmarkProcedural(texture) {
    if (!texture || !texture.userData) return false;
    delete texture.userData[PROCEDURAL_FLAG];
    delete texture.userData[PROCEDURAL_SOURCE];
    return true;
  }

  /* ---------------- texture audits ---------------- */

  /**
   * Audits a single texture. Returns true if compliant, false otherwise.
   * Non-textures return true (nothing to check).
   */
  auditTexture(texture, label) {
    if (!texture) return true;
    if (!_isTexture(texture)) return true;

    this.auditTextureCount++;

    // Allow-list: GPU-generated or engine-internal.
    if (_isRenderTargetTexture(texture)) return true;
    if (_isDepthTexture(texture))        return true;

    // PMREM-generated textures: allowed if policy permits.
    if (this.options.allowPMREM && _isProceduralFlagged(texture)) return true;

    // Compressed textures: always a violation.
    if (_isCompressedTexture(texture)) {
      if (!this.options.allowCompressed) {
        return this._record(
          VIOLATION_KIND.COMPRESSED,
          label || 'compressed texture',
          texture,
          'Compressed textures imply a bitmap source'
        );
      }
      return true;
    }

    // Cube textures: check faces.
    if (_isCubeTexture(texture)) {
      return this._auditCubeTexture(texture, label);
    }

    // Canvas textures: allowed only if marked procedural AND we've verified
    // no image source was drawn into the canvas.
    if (_isCanvasTexture(texture)) {
      if (this.options.allowCanvasTexture && _isProceduralFlagged(texture)) {
        return true;
      }
      return this._record(
        VIOLATION_KIND.CANVAS_TEXTURE,
        label || 'canvas texture',
        texture,
        'CanvasTexture requires markProcedural() + procedural-only canvas'
      );
    }

    // DataTexture: allowed only if marked procedural.
    if (_isDataTexture(texture) || _isDataArrayTexture(texture)) {
      if (_isProceduralFlagged(texture)) return true;
      return this._record(
        VIOLATION_KIND.DATA_TEXTURE_UNMARKED,
        label || 'data texture',
        texture,
        'DataTexture must be marked markProcedural()'
      );
    }

    // Regular Texture: check the .image source.
    const img = texture.image;
    if (!img) return true; // no image yet, still loading — treat as ok

    const tag = Object.prototype.toString.call(img);

    // HTMLImageElement
    if (typeof HTMLImageElement !== 'undefined' && img instanceof HTMLImageElement) {
      return this._record(
        VIOLATION_KIND.HTML_IMAGE_TEXTURE,
        label || 'html image texture',
        texture,
        'src=' + (img.src || '').slice(0, 64)
      );
    }

    // ImageBitmap
    if (typeof ImageBitmap !== 'undefined' && img instanceof ImageBitmap) {
      return this._record(
        VIOLATION_KIND.IMAGE_BITMAP,
        label || 'image bitmap texture',
        texture,
        `size=${img.width}x${img.height}`
      );
    }

    // HTMLVideoElement
    if (typeof HTMLVideoElement !== 'undefined' && img instanceof HTMLVideoElement) {
      return this._record(
        VIOLATION_KIND.VIDEO_TEXTURE,
        label || 'video texture',
        texture,
        'video is not permitted'
      );
    }

    // HTMLCanvasElement not flagged via isCanvasTexture: treat as violation.
    if (typeof HTMLCanvasElement !== 'undefined' && img instanceof HTMLCanvasElement) {
      if (_isProceduralFlagged(texture)) return true;
      return this._record(
        VIOLATION_KIND.CANVAS_TEXTURE,
        label || 'html canvas texture',
        texture,
        `size=${img.width}x${img.height}`
      );
    }

    // OffscreenCanvas
    if (typeof OffscreenCanvas !== 'undefined' && img instanceof OffscreenCanvas) {
      if (_isProceduralFlagged(texture)) return true;
      return this._record(
        VIOLATION_KIND.CANVAS_TEXTURE,
        label || 'offscreen canvas texture',
        texture,
        `size=${img.width}x${img.height}`
      );
    }

    // Unknown image-like object with width/height: treat as suspicious.
    if (typeof img === 'object' && typeof img.width === 'number' && typeof img.height === 'number') {
      if (_isProceduralFlagged(texture)) return true;
      return this._record(
        VIOLATION_KIND.UNKNOWN,
        label || 'unknown image texture',
        texture,
        tag + ' ' + img.width + 'x' + img.height
      );
    }

    return true;
  }

  _auditCubeTexture(cube, label) {
    const faces = cube.image;
    if (!faces) return true;

    // CubeTexture.image may be an array of 6 images or an array of 6
    // { image: ... } objects. Check both shapes.
    const array = Array.isArray(faces) ? faces : null;
    if (!array) return true;

    for (let i = 0; i < array.length; i++) {
      const f = array[i];
      if (!f) continue;
      const img = f.image !== undefined ? f.image : f;
      if (!img) continue;

      if (typeof HTMLImageElement !== 'undefined' && img instanceof HTMLImageElement) {
        return this._record(
          VIOLATION_KIND.CUBE_FROM_IMAGES,
          (label || 'cube texture') + ' face ' + i,
          cube,
          'src=' + (img.src || '').slice(0, 64)
        );
      }
      if (typeof HTMLCanvasElement !== 'undefined' && img instanceof HTMLCanvasElement) {
        if (!_isProceduralFlagged(cube)) {
          return this._record(
            VIOLATION_KIND.CUBE_FROM_IMAGES,
            (label || 'cube texture') + ' face ' + i,
            cube,
            'canvas face'
          );
        }
      }
      if (typeof ImageBitmap !== 'undefined' && img instanceof ImageBitmap) {
        return this._record(
          VIOLATION_KIND.CUBE_FROM_IMAGES,
          (label || 'cube texture') + ' face ' + i,
          cube,
          'image bitmap face'
        );
      }
    }
    return true;
  }

  /* ---------------- material audits ---------------- */

  /**
   * Audits a material for any forbidden map slot. Returns true if compliant.
   */
  auditMaterial(material, label) {
    if (!material) return true;
    this.auditMaterialCount++;

    let ok = true;
    for (let i = 0; i < FORBIDDEN_MATERIAL_MAP_SLOTS.length; i++) {
      const slot = FORBIDDEN_MATERIAL_MAP_SLOTS[i];
      const tex = material[slot];
      if (!tex) continue;

      const slotLabel = (label || material.name || 'material') + '.' + slot;
      if (!this.auditTexture(tex, slotLabel)) {
        ok = false;
        if (slot === 'envMap') {
          this._record(
            VIOLATION_KIND.ENV_MAP,
            slotLabel,
            material,
            'envMap must be procedural (PMREM of procedural sky)'
          );
        } else {
          this._record(
            VIOLATION_KIND.MATERIAL_MAP,
            slotLabel,
            material,
            'material.' + slot + ' must not be bitmap-backed'
          );
        }
      }
    }
    return ok;
  }

  /* ---------------- scene audits ---------------- */

  /**
   * Traverses a scene and audits every material and texture it finds.
   * Returns the number of violations discovered in this pass.
   */
  auditScene(scene, label) {
    if (!scene || typeof scene.traverse !== 'function') return 0;
    this.auditSceneCount++;

    const startViolations = this.violationTotal;

    scene.traverse((obj) => {
      if (!obj) return;

      // Material
      const mat = obj.material;
      if (mat) {
        if (Array.isArray(mat)) {
          for (let i = 0; i < mat.length; i++) {
            this.auditMaterial(mat[i], (label || 'scene') + '/' + (obj.name || 'mesh') + '[' + i + ']');
          }
        } else {
          this.auditMaterial(mat, (label || 'scene') + '/' + (obj.name || 'mesh'));
        }
      }

      // Background texture.
      if (obj === scene && scene.background) {
        if (_isTexture(scene.background)) {
          this.auditTexture(scene.background, 'scene.background');
        }
      }

      // Environment.
      if (obj === scene && scene.environment) {
        if (_isTexture(scene.environment)) {
          this.auditTexture(scene.environment, 'scene.environment');
        }
      }

      // Light shadow maps.
      if (obj.isLight && obj.shadow && obj.shadow.map) {
        // Shadow maps are render-target textures — allowed.
      }

      // Fog textures (FogExp2 / Fog have no textures).
    });

    return this.violationTotal - startViolations;
  }

  /* ---------------- namespace audits ---------------- */

  /**
   * Audits the THREE namespace for forbidden loaders. Returns the number
   * of forbidden loaders found.
   */
  auditThreeNamespace() {
    let found = 0;
    for (let i = 0; i < FORBIDDEN_LOADER_NAMES.length; i++) {
      const name = FORBIDDEN_LOADER_NAMES[i];
      if (typeof THREE[name] !== 'undefined') {
        found++;
        this._record(
          VIOLATION_KIND.LOADER_PRESENT,
          'THREE.' + name,
          THREE[name],
          'bitmap loader present on THREE namespace'
        );
      }
    }
    return found;
  }

  /* ---------------- engine boot hook ---------------- */

  /**
   * Call this once at engine boot. Audits the THREE namespace, then
   * optionally audits a scene if provided.
   */
  enforceNoImageTextures(scene) {
    this.auditCount++;
    const t0 = _now();

    const loaders = this.auditThreeNamespace();
    let sceneViolations = 0;
    if (scene) {
      sceneViolations = this.auditScene(scene, 'boot');
    }

    const t1 = _now();
    this._emit('audit-complete', {
      loaders,
      sceneViolations,
      totalViolations: this.violationTotal,
      durationMs: t1 - t0,
    });

    return {
      loaders,
      sceneViolations,
      totalViolations: this.violationTotal,
      durationMs: t1 - t0,
      ok: this.violationTotal === 0,
    };
  }

  /* ---------------- diagnostics ---------------- */

  isCompliant() {
    return this.violationTotal === 0;
  }

  getRecentViolations(max, out) {
    const n = Math.min(max | 0 || this.violationCount, this.violationCount);
    for (let i = 0; i < n; i++) {
      const idx = (this.violationHead - n + i + this.options.maxViolations) % this.options.maxViolations;
      if (out) {
        out[i] = {
          kind:    VIOLATION_KIND_NAME[this.violations[idx].kind],
          label:   this.violations[idx].label,
          details: this.violations[idx].details,
          frame:   this.violations[idx].frame,
          timeMs:  this.violations[idx].timeMs,
        };
      }
    }
    return n;
  }

  getStats() {
    return {
      mode:                 POLICY_MODE_NAME[this.mode],
      modeIndex:            this.mode,
      compliant:            this.violationTotal === 0,
      violationTotal:       this.violationTotal,
      violationRingCount:   this.violationCount,
      violationRingCap:     this.options.maxViolations,
      auditCount:           this.auditCount,
      auditSceneCount:      this.auditSceneCount,
      auditMaterialCount:   this.auditMaterialCount,
      auditTextureCount:    this.auditTextureCount,
      allowCompressed:      this.options.allowCompressed,
      allowCanvasTexture:   this.options.allowCanvasTexture,
      allowPMREM:           this.options.allowPMREM,
    };
  }

  /* ---------------- reset / dispose ---------------- */

  reset() {
    for (let i = 0; i < this.options.maxViolations; i++) this.violations[i].reset();
    this.violationHead = 0;
    this.violationCount = 0;
    this.violationTotal = 0;
    this.auditCount = 0;
    this.auditSceneCount = 0;
    this.auditMaterialCount = 0;
    this.auditTextureCount = 0;
    this.frame = 0;
    this.lastParanoidFrame = -1;
    return this;
  }

  dispose() {
    this.reset();
    this._listeners.clear();
    return this;
  }
}

