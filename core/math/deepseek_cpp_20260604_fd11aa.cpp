// ============================================================================
// ECS Godot Master Renderer – unified frame rendering pipeline
// ============================================================================
// Orchestrates all rendering subsystems (shadow maps, g‑buffer, lighting,
// voxel GI, sky, water, terrain, vegetation, particles, post‑process,
// temporal upscaling, debug overlay) into a single Godot 4.6 RenderingDevice
// frame graph. Uses entt to discover active components and automatically
// enables/disables passes. All passes are compute or graphics shaders
// generated by the ECS shader compiler. Temporal data is managed by the
// TAAU system. The entire pipeline is parallel‑friendly and uses TBB where
// possible. All math is 64‑bit SIMD‑aligned.
// ============================================================================

